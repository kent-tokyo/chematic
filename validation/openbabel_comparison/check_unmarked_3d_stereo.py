#!/usr/bin/env python3
"""Compare CheMatic and Open Babel on the same source-gated 3D SDF rows.

The manifests and SDFs are generated by
validation/cosmolkit_comparison/check_unmarked_3d_stereo.py. This companion
check does not regenerate or change their RDKit source/reread gate.
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
from pathlib import Path

from rdkit import Chem, RDLogger


def run(*args: str) -> str:
    return subprocess.run(args, check=True, capture_output=True, text=True).stdout


def normalized(smiles: str | None, *, maps: bool, stereo: bool) -> str | None:
    if not smiles:
        return None
    mol = Chem.MolFromSmiles(smiles)
    if mol is None:
        return None
    if not maps:
        for atom in mol.GetAtoms():
            atom.SetAtomMapNum(0)
    if not stereo:
        Chem.RemoveStereochemistry(mol)
    return Chem.MolToSmiles(mol, isomericSmiles=stereo)


def compare(rows: list[dict], che: list[dict], ob: list[str]) -> dict:
    if len(che) != len(rows) or len(ob) != len(rows):
        raise ValueError(f"Record count: source={len(rows)}, CheMatic={len(che)}, Open Babel={len(ob)}")
    hits = {engine: {key: 0 for key in ("strict", "mapless_stereo", "mapless_graph")}
            for engine in ("chematic", "openbabel")}
    misses = {engine: [] for engine in hits}
    for index, row in enumerate(rows):
        expected = row["expected"]
        for engine, raw in (("chematic", che[index].get("smiles")),
                            ("openbabel", ob[index])):
            same = {
                "strict": normalized(raw, maps=True, stereo=True)
                == normalized(expected, maps=True, stereo=True),
                "mapless_stereo": normalized(raw, maps=False, stereo=True)
                == normalized(expected, maps=False, stereo=True),
                "mapless_graph": normalized(raw, maps=False, stereo=False)
                == normalized(expected, maps=False, stereo=False),
            }
            for key, equal in same.items():
                hits[engine][key] += equal
            if not same["mapless_stereo"]:
                misses[engine].append({"index": index, "source_index": row["source_index"],
                                       "category": row["category"], "expected": expected,
                                       "actual": raw, "same_mapless_graph": same["mapless_graph"]})
    return {"hits": hits, "misses": misses, "total": len(rows)}


def analyze_case(manifest: Path, sdf: Path, che_binary: Path, ob_binary: Path,
                 output_prefix: Path, rewrite: bool) -> dict:
    rows = json.loads(manifest.read_text())["rows"]
    tag = sdf.stem
    ob_can = Path(f"{output_prefix}-{tag}.can")
    run(str(ob_binary), "-isdf", str(sdf), "-ocan", "-xn", "-O", str(ob_can))
    ob_rows = [line.split("\t", 1)[0].strip() for line in ob_can.read_text().splitlines()]
    che_rows = json.loads(run(str(che_binary), str(sdf)))
    result = {"source": compare(rows, che_rows, ob_rows)}
    if rewrite:
        rewritten = Path(f"{output_prefix}-{tag}-rewrite.sdf")
        ob_self = Path(f"{output_prefix}-{tag}-rewrite.can")
        write_format = ["-x3"] if "v3000" in tag else []
        run(str(ob_binary), "-isdf", str(sdf), "-osdf", *write_format, "-O", str(rewritten))
        run(str(ob_binary), "-isdf", str(rewritten), "-ocan", "-xn", "-O", str(ob_self))
        ob_rewritten = [line.split("\t", 1)[0].strip()
                        for line in ob_self.read_text().splitlines()]
        che_rewritten = json.loads(run(str(che_binary), str(rewritten)))
        result["openbabel_rewrite"] = compare(rows, che_rewritten, ob_rewritten)
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--case", nargs=2, metavar=("MANIFEST", "SDF"), action="append", required=True)
    parser.add_argument("--chematic", type=Path, required=True)
    parser.add_argument("--openbabel", type=Path, default=Path(shutil.which("obabel") or "obabel"))
    parser.add_argument("--output-prefix", type=Path, required=True)
    parser.add_argument("--rewrite", action="store_true")
    args = parser.parse_args()
    RDLogger.DisableLog("rdApp.*")
    args.output_prefix.parent.mkdir(parents=True, exist_ok=True)
    cases = {Path(sdf).stem: analyze_case(Path(manifest), Path(sdf), args.chematic,
                                         args.openbabel, args.output_prefix, args.rewrite)
             for manifest, sdf in args.case}
    Path(f"{args.output_prefix}-report.json").write_text(json.dumps(cases, indent=2) + "\n")
    print(json.dumps({name: {phase: {engine: result["hits"][engine]
                                     for engine in result["hits"]}
                             for phase, result in phases.items()}
                      for name, phases in cases.items()}, indent=2))


if __name__ == "__main__":
    main()
