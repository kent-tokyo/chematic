#[test]
fn implicit_hydrogens_preserve_water_and_conjugated_cation_heavy_types() {
    for (smiles, types) in [
        ("O", vec![70]),
        ("NC(=[NH2+])N", vec![56, 57, 56, 56]),
        ("[NH2+]=C(N)N", vec![56, 57, 56, 56]),
        ("CC(=[NH2+])N", vec![1, 57, 55, 55]),
        ("N=C(N)N", vec![9, 3, 40, 40]),
        ("CO", vec![1, 6]),
        ("COC", vec![1, 6, 1]),
        ("[OH-]", vec![35]),
        ("[OH3+]", vec![49]),
        ("C=[OH+]", vec![3, 51]),
    ] {
        assert_eq!(
            assign_mmff94_numeric_types(&parse(smiles).unwrap()).unwrap(),
            types,
            "{smiles}"
        );
    }
}
