fn model(smiles: &str) -> Mmff94EnergyModel {
    let mol = chematic_chem::add_hydrogens(&chematic_smiles::parse(smiles).expect("parses"));
    Mmff94EnergyModel::new(&mol).expect("MMFF94 model")
}

#[test]
fn rdkit_convergence_reproduces_rdkits_minimize() {
    for &(smiles, start, want_energy, want_converged) in CASES {
        let model = model(smiles);
        let mut coords = start.to_vec();
        let r = model
            .minimize_bfgs(
                &mut coords,
                200,
                Mmff94Convergence::Rdkit { grad_tol: 1e-4 },
            )
            .unwrap();
        assert!(
            (r.energy - want_energy).abs() <= 1e-6 * want_energy.abs().max(1.0),
            "{smiles}: {} vs RDKit {want_energy}",
            r.energy
        );
        assert_eq!(r.converged, want_converged, "{smiles}");
        assert!((model.energy(&coords) - r.energy).abs() < 1e-9);
    }
}

#[test]
fn max_gradient_convergence_reaches_the_residual_force_threshold() {
    for &(smiles, start, want_energy, _) in CASES {
        let model = model(smiles);
        let mut coords = start.to_vec();
        let r = model
            .minimize_bfgs(&mut coords, 2000, Mmff94Convergence::MaxGradient(1e-4))
            .unwrap();
        assert!(r.converged, "{smiles}");
        let max_g = model
            .bounded_analytic_gradient(&coords)
            .iter()
            .flat_map(|g| g.iter())
            .fold(0.0_f64, |m, g| m.max(g.abs()));
        assert!(max_g < 1e-4, "{smiles}: {max_g}");
        // Same basin as RDKit's 200-iteration geometry, at least as low.
        assert!(r.energy <= want_energy + 1e-6, "{smiles}");
        assert!(r.energy > want_energy - 0.5, "{smiles}");
    }
}

#[test]
fn constraint_rejections_keep_the_last_accepted_geometry() {
    let (smiles, start, _, _) = CASES[0];
    let model = model(smiles);
    let mut coords = start.to_vec();
    let r = model
        .minimize_bfgs_with_constraint(
            &mut coords,
            200,
            Mmff94Convergence::MaxGradient(1e-4),
            |_| false,
        )
        .unwrap();
    assert!(!r.converged);
    assert_eq!(
        r.termination,
        chematic_ff::Mmff94TerminationReason::ConstraintRejectedFallback
    );
    assert_eq!(coords, start.to_vec());
}
