#[test]
fn ignoring_interfragment_pairs_matches_rdkits_default() {
    let (smiles, why, coords, want) = SALT;
    let mol = chematic_chem::add_hydrogens(&chematic_smiles::parse(smiles).expect("parses"));
    let options = chematic_ff::Mmff94Options {
        ignore_interfragment_interactions: true,
    };
    let b = chematic_ff::mmff94_energy_breakdown_with_options(&mol, coords, options).unwrap();
    for (got, want) in [b.vdw, b.electrostatic].into_iter().zip([want[5], want[6]]) {
        assert!(
            (got - want).abs() < 1e-6,
            "{smiles} ({why}): {got} vs RDKit {want}"
        );
    }
    // By default the ions interact.
    let all = chematic_ff::mmff94_energy_breakdown(&mol, coords).unwrap();
    assert!((all.electrostatic - want[6]).abs() > 1.0);
}
