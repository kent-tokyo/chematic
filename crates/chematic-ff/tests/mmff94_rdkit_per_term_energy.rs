#[test]
fn per_term_energies_match_rdkit() {
    for (smiles, why, coords, want) in CASES.iter().chain(CASES_2D) {
        let mol = chematic_chem::add_hydrogens(&chematic_smiles::parse(smiles).expect("parses"));
        let b = chematic_ff::mmff94_energy_breakdown(&mol, coords).expect("typed");
        let got = [
            b.bond,
            b.angle,
            b.stretch_bend,
            b.oop,
            b.torsion,
            b.vdw,
            b.electrostatic,
        ];
        let names = [
            "bond",
            "angle",
            "stretch-bend",
            "oop",
            "torsion",
            "vdw",
            "electrostatic",
        ];
        for k in 0..7 {
            assert!(
                (got[k] - want[k]).abs() < 1e-6 * want[k].abs().max(1.0),
                "{smiles} ({why}): {} {} vs RDKit {}",
                names[k],
                got[k],
                want[k]
            );
        }
    }
}
