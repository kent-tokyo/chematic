/// Look up bond stretching parameters by MMFF94 numeric atom types.
///
/// `bond_type`: 0 for most single bonds; 1 for bonds adjacent to π systems.
/// Pair is normalized (min/max) so argument order does not matter.
pub fn mmff94_bond_energy(bond_type: u8, type_i: u8, type_j: u8) -> Option<BondEnergyParams> {
    let (ti, tj) = if type_i <= type_j {
        (type_i, type_j)
    } else {
        (type_j, type_i)
    };
    MMFF94_BOND_ENERGY
        .binary_search_by_key(&(bond_type, ti, tj), |&(bt, a, b, _, _)| (bt, a, b))
        .ok()
        .map(|idx| {
            let (_, _, _, kb, r0) = MMFF94_BOND_ENERGY[idx];
            BondEnergyParams { kb, r0 }
        })
}

