/// Why a stereocenter or declared E/Z bond could not be evaluated against a geometry.
/// Mirrors `chematic_perception::stereo2d_local::StereoRejectionReason`'s pattern of
/// typed, named rejection (never a silent skip pooled into "no violation found").
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum StereoRejectionReason {
    /// The atom's declared-neighbor-order shape isn't a plain 4-substituent
    /// tetrahedral center (wrong neighbor count, more than one implicit-H sentinel,
    /// an inconsistent implicit-H count, or a non-single/up/down bond among its
    /// neighbors -- e.g. an allene/axial-chirality atom, not a simple tetrahedral one).
    UnsupportedCoordination,
    /// The signed volume (tetrahedral) or dihedral (E/Z) is within its epsilon of
    /// zero/undefined -- a coplanar or otherwise degenerate 3D arrangement.
    DegenerateGeometry,
    /// The three real substituents' bond directions summed to a near-zero vector, so
    /// the implicit-H phantom position's direction is ill-defined.
    DegenerateImplicitHDirection,
    /// The double bond is part of a cumulated system (allene-like: another double
    /// bond at one of its own atoms) -- not a simple E/Z bond. A double bond that is
    /// terminal on at least one end (no real substituent besides the other alkene
    /// atom, e.g. a carbonyl C=O) is filtered out earlier and never reported at all
    /// (it structurally cannot carry declared E/Z, regardless of markers elsewhere
    /// in the molecule -- see `verify_double_bond`'s doc comment), so this variant is
    /// reserved for the cumulated case in practice; kept as one name since both
    /// describe "not a simple E/Z bond".
    TerminalOrCumulatedAlkene,
    /// The bond carries a declared direction marker somewhere, but at least one
    /// alkene terminus has no substituent with an actual `/`/`\` marker (or an
    /// invertible complement) to anchor the comparison.
    AmbiguousDirection,
}

/// Verification outcome for one declared stereocenter or declared E/Z bond.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum StereoStatus {
    /// The 3D geometry reproduces the declared stereo.
    Satisfied,
    /// The 3D geometry contradicts the declared stereo.
    Violated,
    /// Could not be evaluated; see [`StereoRejectionReason`].
    Unevaluable(StereoRejectionReason),
}

impl StereoStatus {
    pub fn is_satisfied(&self) -> bool {
        matches!(self, StereoStatus::Satisfied)
    }
    pub fn is_violated(&self) -> bool {
        matches!(self, StereoStatus::Violated)
    }
}

/// A declared stereocenter (tetrahedral atom) or declared E/Z double bond, identified
/// uniformly for reporting/repair bookkeeping.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum StereoElement {
    Tetrahedral(AtomIdx),
    DoubleBond(BondIdx),
}

/// One declared tetrahedral stereocenter, turned into a constraint a future
/// embedding-time consumer could check or enforce -- independent of any particular
/// geometry (built from `mol` alone). See the "Constraint representation" section
/// near [`build_stereo_constraints`] for how this differs from [`TetrahedralReport`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct TetrahedralConstraint {
    pub atom: AtomIdx,
    /// Declared SMILES chirality-neighbor order (see [`declared_neighbor_order`]);
    /// one entry may be [`STEREO_H_SENTINEL`] for an implicit-H stereocenter. A
    /// consumer resolving this against real coordinates must substitute a phantom
    /// position for that slot the same way [`tetrahedral_positions`] does.
    pub order: [u32; 4],
    /// RDKit-calibrated (see this struct's constructor and the module's
    /// `tetrahedral_matches_rdkit_*` tests): `true` means a satisfying geometry must
    /// produce a NEGATIVE `signed_volume(order[1], order[2], order[3], order[0])`;
    /// `false` means positive. Expressed as the sign directly, not as a `@`/`@@`/CCW
    /// label, so a consumer never has to re-derive the CCW-to-sign mapping that this
    /// module's own sign convention got backwards twice before being pinned against
    /// an external RDKit oracle.
    pub requires_negative_volume: bool,
}

/// One declared E/Z double bond, turned into a constraint a future embedding-time
/// consumer could check or enforce -- independent of any particular geometry. See
/// [`build_stereo_constraints`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct DoubleBondConstraint {
    pub bond: BondIdx,
    pub end1: AtomIdx,
    pub end2: AtomIdx,
    /// The specific direction-marked substituent on `end1`'s side (see
    /// [`marked_substituent`]).
    pub sub1: AtomIdx,
    /// The specific direction-marked substituent on `end2`'s side.
    pub sub2: AtomIdx,
    /// `true` when a satisfying geometry must place `sub1` and `sub2` on the same
    /// side of the `end1`-`end2` axis (dihedral magnitude < 90°, matching
    /// [`verify_double_bond`]'s convention) -- not itself "cis"/"trans" or "Z"/"E",
    /// since those labels depend on CIP priority, which this module deliberately
    /// never resolves (see the module's "Design" doc section).
    pub same_side: bool,
}

/// One tetrahedral center's verification result.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct TetrahedralReport {
    pub atom: AtomIdx,
    pub status: StereoStatus,
}

/// One declared E/Z double bond's verification result.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct DoubleBondReport {
    pub bond: BondIdx,
    pub status: StereoStatus,
}

/// Full verification report for one `(mol, coords)` pair: every atom with declared
/// tetrahedral chirality, and every double bond with a declared `/`/`\` direction
/// marker on at least one adjacent bond -- nothing pooled into a single number.
#[derive(Debug, Clone, Default)]
pub struct StereoVerification {
    pub tetrahedral: Vec<TetrahedralReport>,
    pub double_bond: Vec<DoubleBondReport>,
}

impl StereoVerification {
    pub fn n_declared(&self) -> usize {
        self.tetrahedral.len() + self.double_bond.len()
    }

    pub fn n_satisfied(&self) -> usize {
        self.tetrahedral
            .iter()
            .filter(|r| r.status.is_satisfied())
            .count()
            + self
                .double_bond
                .iter()
                .filter(|r| r.status.is_satisfied())
                .count()
    }

    pub fn n_violations(&self) -> usize {
        self.tetrahedral
            .iter()
            .filter(|r| r.status.is_violated())
            .count()
            + self
                .double_bond
                .iter()
                .filter(|r| r.status.is_violated())
                .count()
    }

    pub fn n_unevaluable(&self) -> usize {
        self.n_declared() - self.n_satisfied() - self.n_violations()
    }

    pub fn violations(&self) -> Vec<StereoElement> {
        let mut out: Vec<StereoElement> = self
            .tetrahedral
            .iter()
            .filter(|r| r.status.is_violated())
            .map(|r| StereoElement::Tetrahedral(r.atom))
            .collect();
        out.extend(
            self.double_bond
                .iter()
                .filter(|r| r.status.is_violated())
                .map(|r| StereoElement::DoubleBond(r.bond)),
        );
        out
    }

    /// `true` when there are zero `Violated` entries (Unevaluable entries don't count
    /// against this -- they're unknown, not contradicted).
    pub fn is_fully_satisfied(&self) -> bool {
        self.n_violations() == 0
    }
}

