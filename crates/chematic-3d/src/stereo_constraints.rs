//! Chiral-volume / improper-torsion stereo constraint verification and repair
//! for already-embedded 3D geometries. 3D Breakthrough Program, Wave 2, Agent D
//! -- see `docs/rfcs/3d_breakthrough_master_plan.md` §0/§3 and `docs/rfcs/etkdg_3d_gap_rfc.md`
//! Phase 3 for the diagnosis this module answers.
//!
//! # What this is
//!
//! Given a `(mol, coords)` pair -- any already-embedded geometry, regardless of
//! which engine produced it -- this module:
//!
//! 1. [`verify_stereo`]: checks every declared tetrahedral (`@`/`@@`) center and every
//!    declared alkene E/Z bond (`/`/`\`) against the actual 3D geometry, and reports a
//!    typed, per-center/per-bond [`StereoStatus`] (never just a pooled boolean).
//! 2. [`repair_stereo`]: for every `Violated` entry, produces a corrected [`Coords3D`]
//!    that satisfies the declared stereo there, moving as little of the rest of the
//!    geometry as possible, and fails closed (typed [`RepairFailureReport`]) rather than
//!    ever returning coordinates that still violate a declared stereo element while
//!    claiming success.
//!
//! This is the module the fail-closed stub in `distance_geometry_v2.rs`
//! (`EmbedFailureCause::StereoConstraintFailed`) exists to be replaced by, once
//! Coordinator wires it in as a Wave 2 integration step. This module does not import
//! from or modify `distance_geometry_v2.rs`; it operates purely on `(mol, coords)`,
//! the same shape `bounds_conformance`/`assign_stereo_from_3d` already use, so it is
//! usable as a post-processing pass over any embedder's output.
//!
//! # Design: raw declared parity, not CIP R/S/E/Z labels
//!
//! `assign_stereo_from_3d` (this crate's existing 3D-to-stereo *perception* function,
//! the opposite direction from this module's job) requires `mol.neighbors(idx).count()
//! == 4` for tetrahedral centers -- i.e. **zero coverage** for any stereocenter with an
//! implicit hydrogen (one heavy neighbor short of 4), which is the majority case in
//! real molecules (L-alanine, ibuprofen, naproxen, menthol, ...) since `Coords3D` is
//! heavy-atom-only and never materializes H (`docs/rfcs/etkdg_3d_gap_rfc.md` §3). Routing
//! this module's verifier through that function would silently make it a no-op on
//! most of its own job.
//!
//! Instead, this module checks the **raw declared parity** directly:
//! `Molecule::stereo_neighbor_order` (the literal SMILES chirality-neighbor order,
//! with [`chematic_core::STEREO_H_SENTINEL`] standing in for an implicit H) plus the
//! `@`/`@@` `Chirality` flag define a signed-volume sign with **no CIP ranking
//! involved at all** -- see `assign_tetrahedral` in `chematic-chem/src/cip.rs`'s own
//! doc comment: "`@@` means: looking FROM neighbors[0], the sequence
//! neighbors[1]→neighbors[2]→neighbors[3] goes clockwise (CW)". Checking whether a 3D
//! geometry reproduces that raw ordering does not require resolving CIP priority, so
//! it works even when CIP ranking would be tied (a real, non-rare failure mode for the
//! project's existing CIP implementations) and covers implicit-H centers via a
//! standard "phantom" position for the missing 4th substituent (the direction
//! opposite the sum of the other three unit bond vectors -- exact for an ideal
//! tetrahedron, where the four unit vectors from the center sum to zero; only the
//! *sign* of the resulting volume matters, not phantom bond length precision).
//!
//! E/Z similarly never needs CIP: a declared `/`/`\` marks a *specific* substituent's
//! side directly (see `substituent_is_up` in `chematic-chem/src/cip.rs`), so this
//! module reproduces that same per-atom up/down convention and compares the declared
//! same-side/opposite-side relationship against the actual dihedral sign -- reusing
//! `stereo3d::dihedral` (already `pub(crate)`, called here rather than duplicated).
//!
//! Sign convention calibrated and verified against an **external oracle** (RDKit
//! `AssignStereochemistryFrom3D`), not derived from the doc comments above or from
//! any internal "CCW/CW when viewed from n0" reasoning -- an earlier version of this
//! module built exactly that reasoning and got the sign backwards, confirmed only
//! after independent review reproduced it against RDKit-embedded, RDKit-re-perception-
//! confirmed conformers (see `tetrahedral_matches_rdkit_*` tests and the PR body's
//! "sign convention correction" section for the full account). Internal hand
//! re-derivations of the same convention independently reproduced the same wrong
//! sign twice, which is why every fixture anchoring this predicate now (this
//! module's tests and `examples/stereo_constraints_gap_check.rs`'s fixture controls)
//! uses coordinates generated by RDKit, not hand-picked ones.
//!
//! # Repair design
//!
//! Tetrahedral: reflect one substituent's *direction* from the center through the
//! plane of the other three, then re-place it at the **original bond length** along
//! that new direction (a plain geometric reflection through that plane, without
//! renormalizing, inflates the bond length by ~67% even for a perfectly ideal
//! tetrahedron -- verified by hand for the regular-tetrahedron case, see PR body --
//! which would itself trip this codebase's bond-length-blowup convention). The moved
//! substituent's entire downstream subtree is translated rigidly by the same
//! displacement, so every bond length/angle *within* that subtree is preserved
//! exactly; only the one bond from the center to that substituent changes.
//!
//! E/Z: rotate one alkene terminus's entire non-double-bond substituent group 180°
//! around the axis through the two double-bond atoms. A rigid rotation about a fixed
//! axis preserves every bond length/angle within the rotated group exactly and
//! guarantees the cis/trans relationship to the other (untouched) terminus flips.
//!
//! Both repairs first verify the chosen substituent/group is a genuine graph bridge
//! (removing the center/terminus bond disconnects it from the rest of the molecule) --
//! translating or rotating part of a ring that closes back through the stereocenter
//! would corrupt the ring closure, so such candidates are rejected, not attempted.
//! Both repairs re-verify the specific element they targeted immediately after
//! applying the transform, and [`repair_stereo`] additionally re-verifies, at the
//! end, both every originally-`Satisfied` element AND every individually-"fixed"
//! element against the final geometry, to catch any cross-element regression --
//! including one repair silently undoing an *already-confirmed* fix on a different
//! element (found on real corpus data: two ring-fused stereocenters whose
//! individually bridge-safe substituents still overlapped enough for this to
//! happen). Never silently returns coordinates that still violate (or newly
//! violate) a declared stereo element while reporting success.

use std::collections::{HashSet, VecDeque};

use chematic_core::{
    AtomIdx, BondIdx, BondOrder, Chirality, Molecule, STEREO_H_SENTINEL, implicit_hcount,
};

use crate::coords::{Coords3D, Point3};

/// Signed-volume magnitude below this (phantom bond length is 1.0, real bond lengths
/// ~1-2 Å, so a genuine tetrahedral volume is order-1 or larger) is treated as a
/// degenerate/coplanar arrangement rather than floating-point noise.
/// Matches `stereo3d.rs`'s own `1e-6` convention for the identical signed-volume test.
const VOLUME_EPS: f64 = 1e-6;

/// Magnitude of the summed unit bond vectors below which the implicit-H phantom
/// direction is considered ill-defined (the three real substituents are arranged too
/// close to symmetric/planar to infer which side the missing 4th substituent is on).
///
/// ponytail: fixed threshold, not a tunable parameter -- revisit if a real corpus
/// molecule needs a different cutoff.
const PHANTOM_DIRECTION_EPS: f64 = 1e-3;

/// Arbitrary unit length for the implicit-H phantom position. Only the *direction*
/// (hence the sign of the resulting signed volume) matters for this module's checks;
/// this is never used as a physically accurate bond length anywhere.
const PHANTOM_BOND_LENGTH: f64 = 1.0;

