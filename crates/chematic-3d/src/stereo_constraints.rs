/// Verify every declared tetrahedral stereocenter and declared E/Z double bond in
/// `mol` against `coords`. See the module docs for the raw-parity (no-CIP) design.
pub fn verify_stereo(mol: &Molecule, coords: &Coords3D) -> StereoVerification {
    let mut tetrahedral = Vec::new();
    for i in 0..mol.atom_count() {
        let idx = AtomIdx(i as u32);
        if mol.atom(idx).chirality == Chirality::None {
            continue;
        }
        tetrahedral.push(TetrahedralReport {
            atom: idx,
            status: verify_tetrahedral_center(mol, coords, idx),
        });
    }

    let mut double_bond = Vec::new();
    for j in 0..mol.bond_count() {
        let bidx = BondIdx(j as u32);
        if let Some(status) = verify_double_bond(mol, coords, bidx) {
            double_bond.push(DoubleBondReport { bond: bidx, status });
        }
    }

    StereoVerification {
        tetrahedral,
        double_bond,
    }
}

