/// Declared SMILES chirality-neighbor order for `idx` (4 entries, one possibly
/// [`STEREO_H_SENTINEL`]). Prefers the parser-recorded `stereo_neighbor_order`
/// (true textual encounter order, ring closures resolved correctly); falls back to
/// adjacency order + the same preceding-atom heuristic `chematic-chem/src/cip.rs`'s
/// private `stereo_neighbors` uses, for molecules built without parse-time stereo
/// data (e.g. directly via `MoleculeBuilder`). Returns `None` only when `idx` has no
/// declared chirality at all.
fn declared_neighbor_order(mol: &Molecule, idx: AtomIdx) -> Option<Vec<u32>> {
    if let Some(order) = mol.stereo_neighbor_order(idx) {
        return Some(order.to_vec());
    }
    let atom = mol.atom(idx);
    if atom.chirality == Chirality::None {
        return None;
    }
    let mut neighbors: Vec<u32> = mol.neighbors(idx).map(|(nb, _)| nb.0).collect();
    let has_bracket_h = atom.hydrogen_count.is_some_and(|h| h > 0);
    if has_bracket_h {
        let has_preceding = neighbors.first().map(|&nb| nb < idx.0).unwrap_or(false);
        let h_pos = if has_preceding { 1 } else { 0 };
        neighbors.insert(h_pos, STEREO_H_SENTINEL);
    }
    Some(neighbors)
}

/// Signed volume of the tetrahedron with vertices p1, p2, p3, p4 -- own copy of
/// `stereo3d.rs`'s (module-private there) formula; identical math (`(p1-p4) . ((p2-p4)
/// x (p3-p4))`), reimplemented here rather than exposing that private fn.
fn signed_volume(p1: Point3, p2: Point3, p3: Point3, p4: Point3) -> f64 {
    let a = p1.sub(&p4);
    let b = p2.sub(&p4);
    let c = p3.sub(&p4);
    a.dot(&b.cross(&c))
}

/// Estimate the position of a missing 4th (implicit-H) substituent: the direction
/// opposite the sum of the other three (unit) bond vectors from `center`. Exact for
/// an ideal tetrahedron (the four unit bond vectors from the center sum to zero);
/// only the resulting *sign* of a signed-volume test is relied on anywhere this is
/// used, never the exact position.
fn phantom_neighbor_position(
    center: Point3,
    real_neighbor_positions: &[Point3],
) -> Result<Point3, StereoRejectionReason> {
    let mut sum = Point3::new(0.0, 0.0, 0.0);
    for &p in real_neighbor_positions {
        let dir = p
            .sub(&center)
            .try_normalize()
            .ok_or(StereoRejectionReason::DegenerateGeometry)?;
        sum = sum.add(&dir);
    }
    let sum_norm = sum.norm();
    if sum_norm < PHANTOM_DIRECTION_EPS {
        return Err(StereoRejectionReason::DegenerateImplicitHDirection);
    }
    let phantom_dir = sum.scale(-1.0 / sum_norm);
    Ok(center.add(&phantom_dir.scale(PHANTOM_BOND_LENGTH)))
}

/// The 4 declared-order positions (real coordinates, or a computed phantom for the
/// implicit-H sentinel slot).
fn tetrahedral_positions(
    coords: &Coords3D,
    center_idx: AtomIdx,
    order: &[u32],
) -> Result<[Point3; 4], StereoRejectionReason> {
    let center = coords.get(center_idx);
    let mut real_positions = [Point3::new(0.0, 0.0, 0.0); 4];
    let mut real_count = 0usize;
    for &neighbor in order {
        if neighbor != STEREO_H_SENTINEL {
            real_positions[real_count] = coords.get(AtomIdx(neighbor));
            real_count += 1;
        }
    }
    let mut out = [Point3::new(0.0, 0.0, 0.0); 4];
    for (i, &n) in order.iter().enumerate() {
        out[i] = if n == STEREO_H_SENTINEL {
            phantom_neighbor_position(center, &real_positions[..real_count])?
        } else {
            coords.get(AtomIdx(n))
        };
    }
    Ok(out)
}

/// Conservative geometric screen for reported, satisfied tetrahedral centers.
/// The central atom must be inside its four-ligand tetrahedron, and all pairs of
/// ligand directions (including a reconstructed implicit ligand) must form
/// angles between 45 and 165 degrees. Carbon with an implicit hydrogen or an
/// explicit hydrogen matching its reconstructed direction additionally needs
/// normalized three-ligand direction volume at least 0.15. This is a coarse
/// screen, not an independent stereo oracle or geometry minimization.
pub fn satisfied_tetrahedral_geometry_is_regular(mol: &Molecule, coords: &Coords3D) -> bool {
    if coords.atom_count() != mol.atom_count() || !coords.is_finite() {
        return false;
    }
    let report = verify_stereo(mol, coords);
    for item in report
        .tetrahedral
        .iter()
        .filter(|r| r.status.is_satisfied())
    {
        if !tetrahedral_geometry_is_regular(mol, coords, item.atom) {
            return false;
        }
    }
    true
}

fn tetrahedral_geometry_is_regular(mol: &Molecule, coords: &Coords3D, atom: AtomIdx) -> bool {
    let Ok(constraint) = tetrahedral_constraint_for(mol, atom) else {
        return false;
    };
    let Ok(p) = tetrahedral_positions(coords, atom, &constraint.order) else {
        return false;
    };
    let center = coords.get(atom);
    if mol.atom(atom).element.atomic_number() == 6 {
        let neighbors: Vec<_> = mol.neighbors(atom).map(|(neighbor, _)| neighbor).collect();
        let implicit_h = neighbors.len() == 3 && mol.implicit_hydrogen_count(atom) == 1;
        let explicit_h = neighbors.len() == 4
            && mol.implicit_hydrogen_count(atom) == 0
            && neighbors
                .iter()
                .filter(|&&n| mol.atom(n).element.atomic_number() == 1)
                .count()
                == 1;
        let directions: Option<Vec<_>> = if implicit_h || explicit_h {
            neighbors
                .iter()
                .copied()
                .filter(|&n| !explicit_h || mol.atom(n).element.atomic_number() != 1)
                .map(|neighbor| coords.get(neighbor).sub(&center).try_normalize())
                .collect()
        } else {
            Some(Vec::new())
        };
        let Some(directions) = directions else {
            return false;
        };
        let matches_reconstruction = if explicit_h {
            let reconstructed = directions[0]
                .add(&directions[1])
                .add(&directions[2])
                .scale(-1.0);
            let hydrogen = neighbors
                .iter()
                .copied()
                .find(|&n| mol.atom(n).element.atomic_number() == 1)
                .expect("explicit_h checked exactly one hydrogen");
            let actual = coords.get(hydrogen).sub(&center).try_normalize();
            reconstructed.norm() >= PHANTOM_DIRECTION_EPS
                && reconstructed
                    .try_normalize()
                    .zip(actual)
                    .is_some_and(|(expected, actual)| {
                        expected.dot(&actual) >= 1.0 - RECONSTRUCTED_H_COSINE_TOLERANCE
                    })
        } else {
            false
        };
        if implicit_h || matches_reconstruction {
            let volume = directions[0]
                .dot(&directions[1].cross(&directions[2]))
                .abs();
            if !volume.is_finite() || volume < MIN_HYDROGEN_BEARING_CARBON_DIRECTION_VOLUME {
                return false;
            }
        }
    }
    let volume = signed_volume(p[0], p[1], p[2], p[3]);
    if !volume.is_finite() || volume.abs() < VOLUME_EPS {
        return false;
    }
    let weights = [
        signed_volume(center, p[1], p[2], p[3]) / volume,
        signed_volume(p[0], center, p[2], p[3]) / volume,
        signed_volume(p[0], p[1], center, p[3]) / volume,
        signed_volume(p[0], p[1], p[2], center) / volume,
    ];
    if weights.iter().any(|w| !w.is_finite() || *w <= 1e-6) {
        return false;
    }
    for i in 0..4 {
        for j in i + 1..4 {
            let Some(a) = p[i].sub(&center).try_normalize() else {
                return false;
            };
            let Some(b) = p[j].sub(&center).try_normalize() else {
                return false;
            };
            let cosine = a.dot(&b);
            if !cosine.is_finite()
                || !(-0.9659258262890683..=core::f64::consts::FRAC_1_SQRT_2).contains(&cosine)
            {
                return false;
            }
        }
    }
    true
}

/// Declared-parity-only prefix of tetrahedral verification, needing no geometry --
/// same gates, same order, as the coords-dependent code that used to precede the
/// geometry check inline. Plain tetrahedral centers and explicitly supported
/// phosphorus, sulfur and selected three-coordinate selenium are in scope. Allene central atoms,
/// which declare axial chirality via bond directions rather than
/// `Atom::chirality`, are handled by the double-bond path instead.
fn supported_stereo_lone_pair(mol: &Molecule, idx: AtomIdx, all_single_ish: bool) -> bool {
    let atom = mol.atom(idx);
    // For the tested three-coordinate neutral sulfur and selenium classes,
    // represent the lone pair opposite the three unit bond vectors.
    let element = atom.element.atomic_number();
    let neutral_chalcogen_lone_pair = matches!(element, 16 | 34)
        && atom.charge == 0
        && (element != 34 || implicit_hcount(mol, idx) == 0)
        && mol.neighbors(idx).count() == 3
        && mol
            .neighbors(idx)
            .filter(|(n, b)| {
                mol.bond(*b).order == BondOrder::Double
                    && match element {
                        16 => matches!(mol.atom(*n).element.atomic_number(), 7 | 8),
                        34 => matches!(mol.atom(*n).element.atomic_number(), 7 | 8 | 16 | 34),
                        _ => false,
                    }
            })
            .count()
            == 1
        && mol.neighbors(idx).all(|(_, b)| {
            matches!(
                mol.bond(b).order,
                BondOrder::Single | BondOrder::Up | BondOrder::Down | BondOrder::Double
            )
        })
        && mol
            .neighbors(idx)
            .filter(|(_, b)| mol.bond(*b).order == BondOrder::Double)
            .count()
            == 1;
    // Three-coordinate selenonium has the same tetrahedral neighbor-order
    // convention as sulfonium for the active lone pair.
    let sulfonium_lone_pair = matches!(atom.element.atomic_number(), 16 | 34)
        && atom.charge == 1
        && mol.neighbors(idx).count() == 3
        && all_single_ish;
    neutral_chalcogen_lone_pair || sulfonium_lone_pair
}

fn tetrahedral_constraint_for(
    mol: &Molecule,
    idx: AtomIdx,
) -> Result<TetrahedralConstraint, StereoRejectionReason> {
    let atom = mol.atom(idx);
    // Only `CounterClockwise`/`Clockwise` are tetrahedral; `SquarePlanar` is
    // also `!= Chirality::None` but must never be coerced into a
    // chiral-volume check decided by `VOLUME_EPS` -- that tolerance is only
    // meaningful for a real tetrahedral arrangement, and treating a
    // square-planar center as "@@ tetrahedral" (the old
    // `requires_negative_volume: atom.chirality == Chirality::CounterClockwise`
    // silently did exactly this, since it's always `false` for
    // `SquarePlanar`) can make `repair_stereo` corrupt a correctly-declared
    // square-planar center. Reusing `UnsupportedCoordination`, the same
    // variant this function already returns a few lines below for other
    // "not a plain tetrahedral center" reasons, means every existing caller's
    // `Unevaluable`-is-"unknown, not contradicted" handling (e.g.
    // `repair_stereo`'s filter) applies for free.
    if !atom.chirality.is_tetrahedral() {
        return Err(StereoRejectionReason::UnsupportedCoordination);
    }

    let all_single_ish = mol.neighbors(idx).all(|(_, bidx)| {
        matches!(
            mol.bond(bidx).order,
            BondOrder::Single | BondOrder::Up | BondOrder::Down
        )
    });
    // Preserve the existing one-double-bond phosphorus case and admit the
    // observed P(-)(=N)(=S) and neutral S(=N)(=O) geometries. Their four
    // actual neighbor positions define tetrahedral parity.
    let double_bonds = mol
        .neighbors(idx)
        .filter(|(_, b)| mol.bond(*b).order == BondOrder::Double)
        .count();
    let has_double_to = |element| {
        mol.neighbors(idx).any(|(n, b)| {
            mol.bond(b).order == BondOrder::Double && mol.atom(n).element.atomic_number() == element
        })
    };
    let supported_four_coordinate = match (atom.element.atomic_number(), atom.charge, double_bonds)
    {
        (15, _, 1) => true,
        (15, -1, 2) => has_double_to(7) && has_double_to(16),
        (16, 0, 2) => has_double_to(7) && has_double_to(8),
        _ => false,
    };
    let four_coordinate_ps = mol.neighbors(idx).count() == 4
        && supported_four_coordinate
        && mol.neighbors(idx).all(|(_, b)| {
            matches!(
                mol.bond(b).order,
                BondOrder::Single | BondOrder::Up | BondOrder::Down | BondOrder::Double
            )
        });
    let stereo_lone_pair = supported_stereo_lone_pair(mol, idx, all_single_ish);
    if !all_single_ish && !four_coordinate_ps && !stereo_lone_pair {
        return Err(StereoRejectionReason::UnsupportedCoordination);
    }

    let Some(mut order) = declared_neighbor_order(mol, idx) else {
        return Err(StereoRejectionReason::UnsupportedCoordination);
    };
    if stereo_lone_pair && order.len() == 3 {
        order.push(STEREO_H_SENTINEL);
    }
    let n_sentinels = order.iter().filter(|&&n| n == STEREO_H_SENTINEL).count();
    if order.len() != 4 || n_sentinels > 1 {
        return Err(StereoRejectionReason::UnsupportedCoordination);
    }
    if n_sentinels == 1 && !stereo_lone_pair && implicit_hcount(mol, idx) != 1 {
        return Err(StereoRejectionReason::UnsupportedCoordination);
    }

    Ok(TetrahedralConstraint {
        atom: idx,
        order: [order[0], order[1], order[2], order[3]],
        // RDKit-calibrated (see module docs and `tetrahedral_matches_rdkit_*`
        // tests): declared `@` (`Chirality::CounterClockwise`) requires a NEGATIVE
        // `signed_volume(order[1], order[2], order[3], order[0])`; `@@` requires
        // positive. Not derived from an internal "CCW/CW when viewed from n0"
        // mental model -- an earlier version of this predicate used that framing
        // and got the sign backwards twice (see git history / PR discussion).
        requires_negative_volume: atom.chirality == Chirality::CounterClockwise,
    })
}

fn verify_tetrahedral_center(mol: &Molecule, coords: &Coords3D, idx: AtomIdx) -> StereoStatus {
    let constraint = match tetrahedral_constraint_for(mol, idx) {
        Ok(c) => c,
        Err(reason) => return StereoStatus::Unevaluable(reason),
    };

    verify_tetrahedral_constraint(coords, &constraint)
}

fn verify_tetrahedral_constraint(
    coords: &Coords3D,
    constraint: &TetrahedralConstraint,
) -> StereoStatus {
    let positions = match tetrahedral_positions(coords, constraint.atom, &constraint.order) {
        Ok(p) => p,
        Err(reason) => return StereoStatus::Unevaluable(reason),
    };

    let volume = signed_volume(positions[1], positions[2], positions[3], positions[0]);
    if volume.abs() < VOLUME_EPS {
        return StereoStatus::Unevaluable(StereoRejectionReason::DegenerateGeometry);
    }
    let actual_negative = volume < 0.0;

    if actual_negative == constraint.requires_negative_volume {
        StereoStatus::Satisfied
    } else {
        StereoStatus::Violated
    }
}

