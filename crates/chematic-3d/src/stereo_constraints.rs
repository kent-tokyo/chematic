/// `true` when `atom_idx` has a double bond other than `exclude_bond` -- i.e. it's
/// part of a cumulated system (allene-like), not a simple isolated alkene terminus.
fn is_cumulated(mol: &Molecule, atom_idx: AtomIdx, exclude_bond: BondIdx) -> bool {
    mol.neighbors(atom_idx)
        .any(|(_, bidx)| bidx != exclude_bond && mol.bond(bidx).order == BondOrder::Double)
}

/// Find a substituent of `alkene_end` (excluding `other_end`) that carries an
/// explicit `/`/`\` direction marker, and whether it is on the "up" side. Mirrors
/// `substituent_is_up` in `chematic-chem/src/cip.rs` (reimplemented here rather than
/// depending on that private fn / pulling in CIP machinery this module doesn't need).
fn marked_substituent(
    mol: &Molecule,
    alkene_end: AtomIdx,
    other_end: AtomIdx,
) -> Option<(AtomIdx, bool)> {
    for (nb, bidx) in mol.neighbors(alkene_end) {
        if nb == other_end {
            continue;
        }
        let bond = mol.bond(bidx);
        if bond.order == BondOrder::Double {
            continue;
        }
        let effective = mol.bond_direction(bidx).unwrap_or(bond.order);
        match effective {
            BondOrder::Up => return Some((nb, bond.atom1 == alkene_end)),
            BondOrder::Down => return Some((nb, bond.atom1 == nb)),
            _ => continue,
        }
    }
    None
}

fn has_any_direction_marker(mol: &Molecule, alkene_end: AtomIdx, other_end: AtomIdx) -> bool {
    mol.neighbors(alkene_end).any(|(nb, bidx)| {
        nb != other_end
            && matches!(
                mol.bond_direction(bidx).unwrap_or(mol.bond(bidx).order),
                BondOrder::Up | BondOrder::Down
            )
    })
}

/// `true` when `atom_idx` has at least one heavy-atom neighbor other than
/// `other_end` -- i.e. it's a genuine, non-terminal alkene end that could plausibly
/// carry its own substituent-direction marker.
fn has_real_substituent(mol: &Molecule, atom_idx: AtomIdx, other_end: AtomIdx) -> bool {
    mol.neighbors(atom_idx).any(|(nb, _)| nb != other_end)
}

/// Declared-parity-only prefix of double-bond verification, needing no geometry --
/// same gates, same order, as the coords-dependent code that used to precede the
/// dihedral check inline (kept behavior-identical on purpose: this is a pure
/// extraction). `None` when `bond_idx` isn't a double bond, or has no declared
/// direction marker anywhere on it (not part of "declared stereo" at all, so not
/// reported -- callers must keep this outer `Option` distinct from the inner
/// `Result`'s `Err`: "not declared" and "declared but unsupported" are different
/// things everywhere else in this module). `Some(Err(..))` for a bond that clearly
/// *is* meant to carry declared E/Z but can't be turned into a constraint.
fn double_bond_constraint_for(
    mol: &Molecule,
    bond_idx: BondIdx,
) -> Option<Result<DoubleBondConstraint, StereoRejectionReason>> {
    let bond = mol.bond(bond_idx);
    if bond.order != BondOrder::Double {
        return None;
    }
    let a1 = bond.atom1;
    let a2 = bond.atom2;

    // A double bond with a terminal end (no substituent besides the other alkene
    // atom -- e.g. a carbonyl C=O, where O has no further substituent) structurally
    // cannot have E/Z stereo, full stop. This check must run BEFORE the marker scan
    // below: without it, a carbonyl carbon that happens to be directly bonded (via a
    // plain single bond) to a DIFFERENT, genuinely stereo-marked alkene elsewhere in
    // the molecule (e.g. `OC(=O)/C=C/c1ccccc1` -- the carbonyl carbon is bonded
    // directly to the alkene carbon carrying that alkene's own `/` marker) gets
    // mistaken for having *its own* declared E/Z, because the marker scan only looks
    // at "is there any Up/Down-marked bond among this atom's neighbors" without
    // checking whose double bond that marker actually belongs to. Found and fixed
    // via this module's own validation harness (`examples/
    // stereo_constraints_gap_check.rs`), not by inspection -- see the PR body.
    //
    // ponytail: this closes the exact cross-contamination pattern observed in the
    // frozen 58-molecule corpus (a C=O directly bonded to a marked alkene carbon).
    // It does not attempt full "which double bond does this single marked bond
    // belong to" disambiguation for the theoretical case of two non-terminal,
    // directly-connected double bonds sharing a marked connector bond (e.g. a
    // conjugated dienone) -- not present in this corpus (re-verified after this fix);
    // revisit if a real molecule needs it.
    if !has_real_substituent(mol, a1, a2) || !has_real_substituent(mol, a2, a1) {
        return None;
    }

    if !has_any_direction_marker(mol, a1, a2) && !has_any_direction_marker(mol, a2, a1) {
        return None; // no declared E/Z on this double bond
    }

    if is_cumulated(mol, a1, bond_idx) || is_cumulated(mol, a2, bond_idx) {
        return Some(Err(StereoRejectionReason::TerminalOrCumulatedAlkene));
    }

    let Some((sub1, up1)) = marked_substituent(mol, a1, a2) else {
        return Some(Err(StereoRejectionReason::AmbiguousDirection));
    };
    let Some((sub2, up2)) = marked_substituent(mol, a2, a1) else {
        return Some(Err(StereoRejectionReason::AmbiguousDirection));
    };

    Some(Ok(DoubleBondConstraint {
        bond: bond_idx,
        end1: a1,
        end2: a2,
        sub1,
        sub2,
        same_side: up1 == up2,
    }))
}

/// `None` when `bond_idx` isn't a double bond, or has no declared direction marker
/// anywhere on it (not part of "declared stereo" at all, so not reported). `Some`
/// otherwise, including `Unevaluable` outcomes for a bond that clearly *is* meant to
/// carry declared E/Z but can't be evaluated.
fn verify_double_bond(
    mol: &Molecule,
    coords: &Coords3D,
    bond_idx: BondIdx,
) -> Option<StereoStatus> {
    let constraint = match double_bond_constraint_for(mol, bond_idx)? {
        Ok(c) => c,
        Err(reason) => return Some(StereoStatus::Unevaluable(reason)),
    };

    Some(verify_double_bond_constraint(coords, &constraint))
}

fn verify_double_bond_constraint(
    coords: &Coords3D,
    constraint: &DoubleBondConstraint,
) -> StereoStatus {
    let Some(angle) = crate::stereo3d::dihedral(
        coords.get(constraint.end1),
        coords.get(constraint.end2),
        coords.get(constraint.sub1),
        coords.get(constraint.sub2),
    ) else {
        return StereoStatus::Unevaluable(StereoRejectionReason::DegenerateGeometry);
    };
    let actual_same_side = angle.abs() < std::f64::consts::FRAC_PI_2;

    if actual_same_side == constraint.same_side {
        StereoStatus::Satisfied
    } else {
        StereoStatus::Violated
    }
}

/// Diagnostic-only detail for one declared E/Z double bond: everything
/// [`verify_double_bond`] computes internally and discards -- the constraint's
/// atom indices, the raw dihedral angle (radians), and the resulting status --
/// plus how far past the hard 90 degree satisfied/violated boundary the actual
/// angle lands (`margin_from_boundary_deg`, always >= 0; small values mean the
/// call is close to the boundary, not a robust result either way). Added for
/// issue #227 Phase 2's BCI-fix stereo-drift investigation
/// (`chembl_tier_b_0082`): production `verify_double_bond`/`verify_stereo`
/// intentionally keep this data internal (a per-atom-index/per-radian API
/// would be a much larger public surface than the raw Satisfied/Violated/
/// Unevaluable status callers need) -- this is purely additive, not called
/// from any production path.
#[derive(Debug, Clone, Copy)]
pub struct DoubleBondDebugInfo {
    pub bond: BondIdx,
    pub end1: AtomIdx,
    pub end2: AtomIdx,
    pub sub1: AtomIdx,
    pub sub2: AtomIdx,
    pub declared_same_side: bool,
    pub actual_angle_rad: f64,
    pub actual_angle_deg: f64,
    pub actual_same_side: bool,
    pub margin_from_boundary_deg: f64,
    pub status: StereoStatus,
}

/// Diagnostic counterpart to [`verify_double_bond`] -- same computation, but
/// returns the full [`DoubleBondDebugInfo`] instead of just [`StereoStatus`].
/// `None` under the identical conditions `verify_double_bond` would return
/// `None` for (not a double bond, or no declared E/Z on it); a bond that *is*
/// declared but unevaluable (e.g. degenerate geometry, ambiguous direction)
/// returns `None` here too, since there is no angle to report -- callers that
/// need the [`StereoRejectionReason`] should call `verify_double_bond`/
/// `verify_stereo` directly.
pub fn debug_double_bond(
    mol: &Molecule,
    coords: &Coords3D,
    bond_idx: BondIdx,
) -> Option<DoubleBondDebugInfo> {
    let constraint = double_bond_constraint_for(mol, bond_idx)?.ok()?;

    let angle = crate::stereo3d::dihedral(
        coords.get(constraint.end1),
        coords.get(constraint.end2),
        coords.get(constraint.sub1),
        coords.get(constraint.sub2),
    )?;
    let actual_same_side = angle.abs() < std::f64::consts::FRAC_PI_2;
    let status = if actual_same_side == constraint.same_side {
        StereoStatus::Satisfied
    } else {
        StereoStatus::Violated
    };
    let boundary_deg = 90.0;
    let angle_deg = angle.to_degrees();
    let margin_from_boundary_deg = (angle_deg.abs() - boundary_deg).abs();

    Some(DoubleBondDebugInfo {
        bond: bond_idx,
        end1: constraint.end1,
        end2: constraint.end2,
        sub1: constraint.sub1,
        sub2: constraint.sub2,
        declared_same_side: constraint.same_side,
        actual_angle_rad: angle,
        actual_angle_deg: angle_deg,
        actual_same_side,
        margin_from_boundary_deg,
        status,
    })
}

/// Diagnostic helper: every declared-E/Z double bond in `mol`, with full
/// [`DoubleBondDebugInfo`] where evaluable. Iterates all bonds (small
/// molecules only -- linear scan, not indexed) rather than requiring the
/// caller to already know which `BondIdx` carries declared E/Z.
pub fn debug_all_double_bonds(mol: &Molecule, coords: &Coords3D) -> Vec<DoubleBondDebugInfo> {
    (0..mol.bond_count())
        .filter_map(|i| debug_double_bond(mol, coords, BondIdx(i as u32)))
        .collect()
}

