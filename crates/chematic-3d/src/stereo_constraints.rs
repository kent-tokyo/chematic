/// Declared SMILES chirality-neighbor order for `idx` (4 entries, one possibly
/// [`STEREO_H_SENTINEL`]). Prefers the parser-recorded `stereo_neighbor_order`
/// (true textual encounter order, ring closures resolved correctly); falls back to
/// adjacency order + the same preceding-atom heuristic `chematic-chem/src/cip.rs`'s
/// private `stereo_neighbors` uses, for molecules built without parse-time stereo
/// data (e.g. directly via `MoleculeBuilder`). Returns `None` only when `idx` has no
/// declared chirality at all.
fn declared_neighbor_order(mol: &Molecule, idx: AtomIdx) -> Option<Vec<u32>> {
    if let Some(order) = mol.stereo_neighbor_order(idx) {
        return Some(order.to_vec());
    }
    let atom = mol.atom(idx);
    if atom.chirality == Chirality::None {
        return None;
    }
    let mut neighbors: Vec<u32> = mol.neighbors(idx).map(|(nb, _)| nb.0).collect();
    let has_bracket_h = atom.hydrogen_count.is_some_and(|h| h > 0);
    if has_bracket_h {
        let has_preceding = neighbors.first().map(|&nb| nb < idx.0).unwrap_or(false);
        let h_pos = if has_preceding { 1 } else { 0 };
        neighbors.insert(h_pos, STEREO_H_SENTINEL);
    }
    Some(neighbors)
}

/// Signed volume of the tetrahedron with vertices p1, p2, p3, p4 -- own copy of
/// `stereo3d.rs`'s (module-private there) formula; identical math (`(p1-p4) . ((p2-p4)
/// x (p3-p4))`), reimplemented here rather than exposing that private fn.
fn signed_volume(p1: Point3, p2: Point3, p3: Point3, p4: Point3) -> f64 {
    let a = p1.sub(&p4);
    let b = p2.sub(&p4);
    let c = p3.sub(&p4);
    a.dot(&b.cross(&c))
}

/// Estimate the position of a missing 4th (implicit-H) substituent: the direction
/// opposite the sum of the other three (unit) bond vectors from `center`. Exact for
/// an ideal tetrahedron (the four unit bond vectors from the center sum to zero);
/// only the resulting *sign* of a signed-volume test is relied on anywhere this is
/// used, never the exact position.
fn phantom_neighbor_position(
    center: Point3,
    real_neighbor_positions: &[Point3],
) -> Result<Point3, StereoRejectionReason> {
    let mut sum = Point3::new(0.0, 0.0, 0.0);
    for &p in real_neighbor_positions {
        let dir = p
            .sub(&center)
            .try_normalize()
            .ok_or(StereoRejectionReason::DegenerateGeometry)?;
        sum = sum.add(&dir);
    }
    let sum_norm = sum.norm();
    if sum_norm < PHANTOM_DIRECTION_EPS {
        return Err(StereoRejectionReason::DegenerateImplicitHDirection);
    }
    let phantom_dir = sum.scale(-1.0 / sum_norm);
    Ok(center.add(&phantom_dir.scale(PHANTOM_BOND_LENGTH)))
}

/// The 4 declared-order positions (real coordinates, or a computed phantom for the
/// implicit-H sentinel slot).
fn tetrahedral_positions(
    coords: &Coords3D,
    center_idx: AtomIdx,
    order: &[u32],
) -> Result<[Point3; 4], StereoRejectionReason> {
    let center = coords.get(center_idx);
    let mut real_positions = [Point3::new(0.0, 0.0, 0.0); 4];
    let mut real_count = 0usize;
    for &neighbor in order {
        if neighbor != STEREO_H_SENTINEL {
            real_positions[real_count] = coords.get(AtomIdx(neighbor));
            real_count += 1;
        }
    }
    let mut out = [Point3::new(0.0, 0.0, 0.0); 4];
    for (i, &n) in order.iter().enumerate() {
        out[i] = if n == STEREO_H_SENTINEL {
            phantom_neighbor_position(center, &real_positions[..real_count])?
        } else {
            coords.get(AtomIdx(n))
        };
    }
    Ok(out)
}

/// Declared-parity-only prefix of tetrahedral verification, needing no geometry --
/// same gates, same order, as the coords-dependent code that used to precede the
/// geometry check inline (kept behavior-identical on purpose: this is a pure
/// extraction, see the PR that introduced [`TetrahedralConstraint`] for the
/// before/after test evidence). Only a plain tetrahedral center (single/up/down
/// bonds only) is in scope -- mirrors `stereo3d.rs`'s `assign_stereo_from_3d` gate,
/// excluding e.g. allene central atoms (which declare axial chirality via bond
/// directions, not `Atom::chirality`, and are handled by the double-bond path
/// instead).
fn tetrahedral_constraint_for(
    mol: &Molecule,
    idx: AtomIdx,
) -> Result<TetrahedralConstraint, StereoRejectionReason> {
    let atom = mol.atom(idx);
    // Only `CounterClockwise`/`Clockwise` are tetrahedral; `SquarePlanar` is
    // also `!= Chirality::None` but must never be coerced into a
    // chiral-volume check decided by `VOLUME_EPS` -- that tolerance is only
    // meaningful for a real tetrahedral arrangement, and treating a
    // square-planar center as "@@ tetrahedral" (the old
    // `requires_negative_volume: atom.chirality == Chirality::CounterClockwise`
    // silently did exactly this, since it's always `false` for
    // `SquarePlanar`) can make `repair_stereo` corrupt a correctly-declared
    // square-planar center. Reusing `UnsupportedCoordination`, the same
    // variant this function already returns a few lines below for other
    // "not a plain tetrahedral center" reasons, means every existing caller's
    // `Unevaluable`-is-"unknown, not contradicted" handling (e.g.
    // `repair_stereo`'s filter) applies for free.
    if !atom.chirality.is_tetrahedral() {
        return Err(StereoRejectionReason::UnsupportedCoordination);
    }

    let all_single_ish = mol.neighbors(idx).all(|(_, bidx)| {
        matches!(
            mol.bond(bidx).order,
            BondOrder::Single | BondOrder::Up | BondOrder::Down
        )
    });
    if !all_single_ish {
        return Err(StereoRejectionReason::UnsupportedCoordination);
    }

    let Some(order) = declared_neighbor_order(mol, idx) else {
        return Err(StereoRejectionReason::UnsupportedCoordination);
    };
    let n_sentinels = order.iter().filter(|&&n| n == STEREO_H_SENTINEL).count();
    if order.len() != 4 || n_sentinels > 1 {
        return Err(StereoRejectionReason::UnsupportedCoordination);
    }
    if n_sentinels == 1 && implicit_hcount(mol, idx) != 1 {
        return Err(StereoRejectionReason::UnsupportedCoordination);
    }

    Ok(TetrahedralConstraint {
        atom: idx,
        order: [order[0], order[1], order[2], order[3]],
        // RDKit-calibrated (see module docs and `tetrahedral_matches_rdkit_*`
        // tests): declared `@` (`Chirality::CounterClockwise`) requires a NEGATIVE
        // `signed_volume(order[1], order[2], order[3], order[0])`; `@@` requires
        // positive. Not derived from an internal "CCW/CW when viewed from n0"
        // mental model -- an earlier version of this predicate used that framing
        // and got the sign backwards twice (see git history / PR discussion).
        requires_negative_volume: atom.chirality == Chirality::CounterClockwise,
    })
}

fn verify_tetrahedral_center(mol: &Molecule, coords: &Coords3D, idx: AtomIdx) -> StereoStatus {
    let constraint = match tetrahedral_constraint_for(mol, idx) {
        Ok(c) => c,
        Err(reason) => return StereoStatus::Unevaluable(reason),
    };

    verify_tetrahedral_constraint(coords, &constraint)
}

fn verify_tetrahedral_constraint(
    coords: &Coords3D,
    constraint: &TetrahedralConstraint,
) -> StereoStatus {
    let positions = match tetrahedral_positions(coords, constraint.atom, &constraint.order) {
        Ok(p) => p,
        Err(reason) => return StereoStatus::Unevaluable(reason),
    };

    let volume = signed_volume(positions[1], positions[2], positions[3], positions[0]);
    if volume.abs() < VOLUME_EPS {
        return StereoStatus::Unevaluable(StereoRejectionReason::DegenerateGeometry);
    }
    let actual_negative = volume < 0.0;

    if actual_negative == constraint.requires_negative_volume {
        StereoStatus::Satisfied
    } else {
        StereoStatus::Violated
    }
}

