    #[test]
    fn coplanar_neighbors_is_degenerate_not_silently_satisfied() {
        let m = mol("[C@](Br)(Cl)(F)I");
        let order = m.stereo_neighbor_order(AtomIdx(0)).unwrap();
        let mut coords = Coords3D::new_zeroed(m.atom_count());
        coords.set(AtomIdx(0), Point3::new(0.0, 0.0, 0.0));
        // All 4 substituents coplanar (z=0) -> degenerate signed volume.
        coords.set(AtomIdx(order[0]), Point3::new(1.0, 0.0, 0.0));
        coords.set(AtomIdx(order[1]), Point3::new(-1.0, 0.0, 0.0));
        coords.set(AtomIdx(order[2]), Point3::new(0.0, 1.0, 0.0));
        coords.set(AtomIdx(order[3]), Point3::new(0.0, -1.0, 0.0));

        let report = verify_stereo(&m, &coords);
        assert_eq!(
            report.tetrahedral[0].status,
            StereoStatus::Unevaluable(StereoRejectionReason::DegenerateGeometry)
        );
    }

