    #[test]
    fn tetrahedral_rdkit_quaternary_flips_for_opposite_declared_tag() {
        // Same RDKit-confirmed-correct-for-`@` coordinates, but paired with the
        // OPPOSITE declared tag (`@@`) -> must read Violated. Proves the predicate
        // discriminates rather than always returning Satisfied.
        let m_wrong_tag = mol("[C@@](Br)(Cl)(F)I");
        let coords = rdkit_quaternary_ccw_coords(&m_wrong_tag);
        let report = verify_stereo(&m_wrong_tag, &coords);
        assert_eq!(report.tetrahedral[0].status, StereoStatus::Violated);
        assert_eq!(
            report.violations(),
            vec![StereoElement::Tetrahedral(report.tetrahedral[0].atom)]
        );
    }

    #[test]
    fn tetrahedral_swapped_rdkit_coords_violate() {
        // Swapping two substituent positions in an RDKit-confirmed-correct geometry
        // is a mechanically guaranteed sign flip (odd permutation of the signed-
        // volume arguments), independent of any CCW/CW framing -- must be Violated.
        let m = mol("[C@](Br)(Cl)(F)I");
        let mut coords = rdkit_quaternary_ccw_coords(&m);
        let p1 = coords.get(AtomIdx(1));
        let p2 = coords.get(AtomIdx(2));
        coords.set(AtomIdx(1), p2);
        coords.set(AtomIdx(2), p1);
        let report = verify_stereo(&m, &coords);
        assert_eq!(report.tetrahedral[0].status, StereoStatus::Violated);
    }

