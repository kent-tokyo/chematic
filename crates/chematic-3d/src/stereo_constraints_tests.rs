    #[test]
    fn implicit_h_stereocenter_evaluable_and_direction_sensitive() {
        // L-alanine: N[C@@H](C)C(=O)O -- 3 heavy neighbors + 1 implicit H at atom 1.
        // Coordinates: RDKit ETKDGv3-embedded, MMFF-optimized (all-atom, heavy atoms
        // only used below -- Coords3D is heavy-atom-only), confirmed by RDKit's own
        // `Chem.AssignStereochemistryFrom3D` to reproduce the declared `@@` (S)
        // configuration. This is the ground truth this test checks against -- not a
        // hand-derived phantom-position computation (which independently reproduced
        // the same inverted sign this module's core predicate had, see PR body).
        let m = mol("N[C@@H](C)C(=O)O");
        let idx = AtomIdx(1);
        assert_ne!(m.atom(idx).chirality, Chirality::None);
        assert_eq!(chematic_core::implicit_hcount(&m, idx), 1);

        let order = m.stereo_neighbor_order(idx).expect("stereo order recorded");
        assert_eq!(order.len(), 4);
        assert_eq!(order.iter().filter(|&&n| n == STEREO_H_SENTINEL).count(), 1);

        let mut coords = Coords3D::new_zeroed(m.atom_count());
        coords.set(AtomIdx(0), Point3::new(-1.029655, -1.350290, 0.249121)); // N
        coords.set(idx, Point3::new(-0.278484, -0.251876, -0.400037)); // C (stereocenter)
        coords.set(AtomIdx(2), Point3::new(-0.983462, 1.068581, -0.122130)); // C (methyl)
        coords.set(AtomIdx(3), Point3::new(1.164492, -0.221382, 0.114110)); // C (carboxyl)
        coords.set(AtomIdx(4), Point3::new(1.656783, -0.980050, 0.936364)); // O
        coords.set(AtomIdx(5), Point3::new(1.916290, 0.736776, -0.462302)); // O

        let report = verify_stereo(&m, &coords);
        let status = report
            .tetrahedral
            .iter()
            .find(|r| r.atom == idx)
            .unwrap()
            .status;
        assert_eq!(
            status,
            StereoStatus::Satisfied,
            "RDKit confirmed this geometry reproduces declared `@@` -- must be Satisfied, got {status:?}"
        );

        // Swapping two real substituent positions is a mechanically guaranteed sign
        // flip (odd permutation) -- must read Violated, proving the phantom-H
        // placement is actually direction-sensitive rather than degenerate/ignored.
        let mut coords2 = coords.clone();
        let p2 = coords2.get(AtomIdx(2));
        let p3 = coords2.get(AtomIdx(3));
        coords2.set(AtomIdx(2), p3);
        coords2.set(AtomIdx(3), p2);
        let report2 = verify_stereo(&m, &coords2);
        let status2 = report2
            .tetrahedral
            .iter()
            .find(|r| r.atom == idx)
            .unwrap()
            .status;
        assert_eq!(
            status2,
            StereoStatus::Violated,
            "swapping two real substituents must flip the verdict to Violated, got {status2:?}"
        );
    }

