    fn bridge_component_rejects_ring_closing_path() {
        // A 4-membered ring where every neighbor of atom 0 eventually loops back:
        // bridge_component from one ring neighbor, forbidding the other, must
        // detect the loop and return None.
        let m = mol("C1CCC1");
        // atom0's neighbors are atom1 and atom3 (ring). BFS from atom1, blocked=atom0,
        // forbidden=[atom3] must reach atom3 via atom1->atom2->atom3.
        let result = bridge_component(&m, &[AtomIdx(1)], AtomIdx(0), &[AtomIdx(3)]);
        assert!(
            result.is_none(),
            "ring-closing path must be detected, not treated as a bridge"
        );
    }

    #[test]
    fn bridge_component_accepts_genuine_branch() {
        // Butane: atom0-atom1-atom2-atom3, no ring. BFS from atom0 (blocked=atom1,
        // forbidden=[]) must succeed trivially (atom0 is a genuine leaf branch).
        let m = mol("CCCC");
        let result = bridge_component(&m, &[AtomIdx(0)], AtomIdx(1), &[]);
        assert!(result.is_some());
        assert_eq!(
            result.unwrap(),
            [AtomIdx(0)].into_iter().collect::<HashSet<_>>()
        );
    }

