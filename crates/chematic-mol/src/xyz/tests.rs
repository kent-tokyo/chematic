#[test]
fn multi_frame_survives_crlf_and_missing_final_newline() {
    // Middle frame uses CRLF line endings; the whole trajectory has no
    // trailing newline after the last atom row. Both boundary cases
    // that could desync a naive two-pass line scanner.
    let traj = "1\nlf frame\nH 0.0 0.0 0.0\n\
                     2\r\ncrlf frame\r\nO 0.0 0.0 0.0\r\nH 1.0 0.0 0.0\r\n\
                     0\nempty frame\n\
                     1\nno trailing newline\nC 1.0 2.0 3.0";
    let frames = parse_xyz_all(traj).unwrap();
    assert_eq!(frames.len(), 4);
    assert_eq!(frames[0].atoms.len(), 1);
    assert_eq!(frames[1].atoms.len(), 2);
    assert_eq!(frames[1].comment, "crlf frame");
    assert!(frames[2].atoms.is_empty());
    assert_eq!(frames[3].atoms.len(), 1);
    assert_eq!(frames[3].atoms[0].element, Element::C);
    assert_eq!(frames[3].atoms[0].z, 3.0);
}

