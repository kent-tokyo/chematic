const WATER_XYZ: &str = "3\nwater\nO 0.00000000 0.00000000 0.00000000\nH 0.75860000 0.00000000 0.50428400\nH 0.75860000 0.00000000 -0.50428400\n";

const METHANE_XYZ: &str = "5\nmethane, generated by chematic\nC 0.00000000 0.00000000 0.00000000\nH 0.62910000 0.62910000 0.62910000\nH -0.62910000 -0.62910000 0.62910000\nH -0.62910000 0.62910000 -0.62910000\nH 0.62910000 -0.62910000 -0.62910000\n";

#[test]
fn parse_water_fixture() {
    let frame = parse_xyz(WATER_XYZ).unwrap();
    assert_eq!(frame.comment, "water");
    assert_eq!(frame.atoms.len(), 3);
    assert_eq!(frame.atoms[0].element, Element::O);
    assert_eq!(frame.atoms[1].element, Element::H);
    assert_eq!(frame.atoms[2].element, Element::H);
    assert_eq!(frame.atoms[0].x, 0.0);
    assert_eq!(frame.atoms[1].x, 0.7586);
    assert_eq!(frame.atoms[2].z, -0.504284);

    let mol = frame.to_molecule();
    assert_eq!(mol.atom_count(), 3);
    assert_eq!(mol.atom(chematic_core::AtomIdx(0)).element, Element::O);
    assert_eq!(mol.atom(chematic_core::AtomIdx(1)).element, Element::H);
    assert_eq!(mol.atom(chematic_core::AtomIdx(2)).element, Element::H);
    assert_eq!(mol.bond_count(), 0);

    let coords = frame.coords();
    assert_eq!(coords.len(), 3);
    assert_eq!(coords[0], (0.0, 0.0, 0.0));
}

