#[test]
fn write_extxyz_accepts_info_value_with_whitespace_but_no_quote() {
    // The exact case that motivated the '"'-rejection check: a value
    // needing quotes (has whitespace) but free of the one character
    // that would corrupt the quoting itself.
    let frame = XyzFrame {
        atoms: vec![XyzAtom {
            element: Element::C,
            x: 0.0,
            y: 0.0,
            z: 0.0,
        }],
        comment: String::new(),
        lattice: None,
        properties: Vec::new(),
        info: vec![("note".to_string(), "hello world".to_string())],
    };
    let written = write_extxyz(&frame).unwrap();
    let reparsed = parse_extxyz(&written).unwrap();
    assert_eq!(reparsed.info, frame.info);
}

#[test]
fn xyz_parse_limits_reject_input_atoms_lines_and_frames() {
    let limits = XyzParseLimits {
        max_input_bytes: 2,
        ..XyzParseLimits::default()
    };
    assert!(matches!(
        parse_xyz_with_limits(WATER_XYZ, &limits),
        Err(XyzError::ResourceLimit {
            resource: "input bytes",
            ..
        })
    ));

    let limits = XyzParseLimits {
        max_atoms_per_frame: 1,
        ..XyzParseLimits::default()
    };
    assert!(matches!(
        parse_xyz_with_limits(WATER_XYZ, &limits),
        Err(XyzError::ResourceLimit {
            resource: "atoms per frame",
            ..
        })
    ));

    let limits = XyzParseLimits {
        max_line_bytes: 2,
        ..XyzParseLimits::default()
    };
    assert!(matches!(
        parse_extxyz_with_limits(WATER_XYZ, &limits),
        Err(XyzError::ResourceLimit {
            resource: "line bytes",
            ..
        })
    ));

    let limits = XyzParseLimits {
        max_frames: 1,
        ..XyzParseLimits::default()
    };
    let trajectory = format!("{WATER_XYZ}{WATER_XYZ}");
    assert!(matches!(
        parse_xyz_all_with_limits(&trajectory, &limits),
        Err(XyzError::ResourceLimit {
            resource: "frames",
            ..
        })
    ));
}
